const fs = require('fs');
const path = require('path');
const crypto = require('crypto');
const { spawnSync } = require('child_process');

function validateWindowsAcl(target, kind, create = false) {
  const root = process.env.SystemRoot || process.env.SYSTEMROOT || process.env.WINDIR;
  if (!root) throw new Error('IPC_ACL_UNAVAILABLE: SystemRoot missing');
  const powershell = path.join(root, 'System32', 'WindowsPowerShell', 'v1.0', 'powershell.exe');
  const args = ['-NoProfile', '-NonInteractive', '-ExecutionPolicy', 'Bypass', '-File', path.join(__dirname, 'ipc-private-acl.ps1'), '-LiteralPath', target, '-Kind', kind];
  if (create) args.push('-Create');
  const result = spawnSync(powershell, args, { windowsHide: true, encoding: 'utf8', timeout: 15000 });
  if (result.error || result.status !== 0) throw new Error('IPC_ACL_INVALID: protected local control path not verified');
}

function assertPrivateDirectory(target, create = false) {
  target = path.resolve(target);
  if (create && !fs.existsSync(path.dirname(target))) fs.mkdirSync(path.dirname(target), { recursive: true, mode: 0o700 });
  if (process.platform === 'win32') {
    validateWindowsAcl(target, 'Directory', create);
  } else {
    if (create) {
      try { fs.mkdirSync(target, { mode: 0o700 }); } catch (err) { if (err.code !== 'EEXIST') throw err; }
    }
    const stat = fs.lstatSync(target);
    if (!stat.isDirectory() || stat.isSymbolicLink() || stat.uid !== process.getuid() || (stat.mode & 0o077) !== 0) {
      throw new Error('IPC_ACL_INVALID: private control directory not verified');
    }
  }
  return target;
}

function assertPrivateFile(target) {
  const stat = fs.lstatSync(target);
  if (!stat.isFile() || stat.isSymbolicLink()) throw new Error('IPC_FILE_INVALID: not a regular file');
  if (process.platform === 'win32') validateWindowsAcl(target, 'File');
  else if (stat.uid !== process.getuid() || (stat.mode & 0o077) !== 0) throw new Error('IPC_ACL_INVALID: private control file not verified');
}

function atomicJson(target, value) {
  const temp = target + '.' + process.pid + '.' + crypto.randomBytes(8).toString('hex') + '.tmp';
  try {
    fs.writeFileSync(temp, JSON.stringify(value), { flag: 'wx', mode: 0o600 });
    fs.renameSync(temp, target);
  } finally {
    try { fs.unlinkSync(temp); } catch {}
  }
}

function readBoundedJson(target, maxBytes) {
  const stat = fs.lstatSync(target);
  if (!stat.isFile() || stat.isSymbolicLink() || stat.size > maxBytes) throw new Error('IPC_FILE_INVALID');
  const data = fs.readFileSync(target, 'utf8');
  if (Buffer.byteLength(data, 'utf8') > maxBytes) throw new Error('IPC_PAYLOAD_TOO_LARGE');
  return JSON.parse(data);
}

function mailboxPath(controlDir, hash, instanceId) {
  if (!/^[a-f0-9]{64}$/.test(hash) || !/^[a-f0-9]{32}$/.test(instanceId)) throw new Error('IPC_IDENTITY_INVALID');
  return path.join(controlDir, hash + '.' + instanceId + '.ipc');
}

async function sendMailboxRequest(endpoint, payload, timeoutMs) {
  const requestId = crypto.randomBytes(16).toString('hex');
  const requestPath = path.join(endpoint, 'req-' + requestId + '.json');
  const responsePath = path.join(endpoint, 'resp-' + requestId + '.json');
  const request = { ...payload };
  if (Buffer.byteLength(JSON.stringify(request), 'utf8') > 4096) throw new Error('IPC_PAYLOAD_TOO_LARGE');
  atomicJson(requestPath, request);
  const deadline = Date.now() + timeoutMs;
  try {
    while (Date.now() < deadline) {
      if (fs.existsSync(responsePath)) return readBoundedJson(responsePath, 65536);
      await new Promise(resolve => setTimeout(resolve, 50));
    }
    throw new Error('IPC_TIMEOUT: mailbox response not confirmed');
  } finally {
    // Only clean the two unique paths generated by this client, never other requests.
    try { fs.unlinkSync(requestPath); } catch {}
    try { fs.unlinkSync(responsePath); } catch {}
  }
}

module.exports = { assertPrivateDirectory, assertPrivateFile, atomicJson, readBoundedJson, mailboxPath, sendMailboxRequest };
